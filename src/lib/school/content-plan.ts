// School content — persistence plan (26 Sep 2026).
//
// Pure: the exact rows scripts/school-content-batch.ts writes once a reply
// has passed content-parse.ts, so the tests pin them without a database.
//
//   Notes → TopicTeachingNote (1:1 by topicId; what /exams/[code]/topics/
//   [topicCode] renders through hasUsableNotes). generatedBy is the tag
//   "school-batch:<model>". The model has no metadata column, so the
//   provenance blob (class, book, chapter, official URL, prompt version, run)
//   travels as an HTML comment at the end of the markdown: invisible when
//   rendered, greppable in the DB, and the journal holds the same record.
//   A re-generation (--force) resets validatedAt / validatorId exactly as
//   scripts/generate-topic-notes.ts does — the content changed.
//
//   Questions → Question rows: validated:false, source AI_GENERATED (the
//   enum's "generated by Claude, awaiting validation"), tags [<chapter
//   code>, "school", "gen:<date>"] plus the model's own kebab tags, and
//   metadata.provenance in the factory's spirit (pipeline, generatedBy,
//   groundedSources, producedAt) with a `school` block and an honest
//   `label`. The verify runner later adds metadata.factoryVerify beside it
//   and flips validated on ACCEPT — that is the only door to "served", and
//   even then the SCHOOL_BOARD exam stays inactive (founder rule 5).

import type { Prisma } from "@prisma/client";
import { PROVENANCE_COMMENT_PREFIX, type NotesProvenance } from "./provenance";
import type { CandidateQuestion } from "../ai/factory/types";
import { MCQ_PROMPT_VERSION, MCQ_SET_SIZE, MCQ_SETS_PER_CHAPTER, MCQ_SET_MIX, NOTES_PROMPT_VERSION, type DifficultyMix, type SchoolChapter, chapterIdentity } from "./content-prompts";

export const SCHOOL_PIPELINE = "school-batch-v1";
export const SCHOOL_TAG = "school";
/** The tag every question of one generation day carries, e.g. gen:2026-09-26. */
export function genTag(now: Date): string {
  return `gen:${now.toISOString().slice(0, 10)}`;
}
export function notesGeneratedBy(model: string): string {
  return `school-batch:${model}`;
}

