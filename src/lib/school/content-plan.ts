/** Sets (0-based indexes) a chapter still needs to reach the target. `existing` = questions already on the chapter (withdrawn ones excluded). --force asks for the full four regardless. */
export function setsNeeded(existing: number, opts: { target?: number; force?: boolean } = {}): number[] {
  const target = opts.target ?? MCQ_SET_SIZE * MCQ_SETS_PER_CHAPTER;
  if (opts.force) return Array.from({ length: MCQ_SETS_PER_CHAPTER }, (_, i) => i);
  const missing = Math.max(0, target - existing);
  const n = Math.min(MCQ_SETS_PER_CHAPTER, Math.ceil(missing / MCQ_SET_SIZE));
  return Array.from({ length: n }, (_, i) => i);
}

/** The mix every set asks for (each set is 4/4/2, so the sum over four sets is the chapter's 16/16/8). */
export function mixForSet(_setIndex: number): DifficultyMix {
  return { ...MCQ_SET_MIX };
}

// ── Resume ──────────────────────────────────────────────────────────────

/** The slice of a journal the resume pruning reads (src/lib/ai/batch.ts BatchJournal, structurally). */
export interface ResumeView {
  requests: Record<string, { customId: string; phase: string; questionId: string; runIndex?: number; status: string }>;
  outputs: {
    notes: Record<string, unknown>;
    notesWritten: Record<string, unknown>;
    gen: Record<string, Record<string, unknown>>;
    written: Record<string, Record<string, unknown>>;
  };
  /** No batch was ever submitted and no submit is pending: nothing was paid for. */
  neverSubmitted: boolean;
}

/**
 * custom_ids of "built" requests a resumed run must NOT submit:
 *   • the run already produced their output (a notes reply parsed or written;
 *     a set parsed or its rows written) — a resume re-enters the phase driver,
 *     which would otherwise submit them again;
 *   • the journal was never submitted (a dry-run journal) and the chapter no
 *     longer needs them — e.g. the 124-chapter dry-run journal resumed after
 *     the 5-chapter pilot wrote those chapters' notes and questions.
 * A request in a journal that HAS submitted batches is kept whatever the DB
 * now holds: mid-run, this run's own earlier writes are what changed the counts.
 */
export function pruneBuiltRequests(
  j: ResumeView,
  need: { notes: Set<string>; sets: Map<string, number[]> },
  phases: { notes: string; gen: string },
): string[] {
  const drop: string[] = [];
  for (const r of Object.values(j.requests)) {
    if (r.status !== "built") continue;
    const set = String(r.runIndex ?? 0);
    const done =
      r.phase === phases.notes
        ? Boolean(j.outputs.notes[r.questionId] || j.outputs.notesWritten[r.questionId])
        : r.phase === phases.gen
          ? Boolean(j.outputs.gen[r.questionId]?.[set] || j.outputs.written[r.questionId]?.[set])
          : false;
    const stale =
      j.neverSubmitted &&
      (r.phase === phases.notes ? !need.notes.has(r.questionId) : r.phase === phases.gen ? !(need.sets.get(r.questionId) ?? []).includes(r.runIndex ?? 0) : false);
    if (done || stale) drop.push(r.customId);
  }
  return drop;
}
