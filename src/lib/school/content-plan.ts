// 26 Sep 2026: the provenance comment helpers moved to ./provenance so the
// school pages can strip the comment without importing this file (it pulls
// content-prompts.ts and the Anthropic client). Same names, re-exported.
export { PROVENANCE_COMMENT_PREFIX, readProvenanceComment, stripProvenanceComment } from "./provenance";
export type { NotesProvenance } from "./provenance";

export function notesProvenance(ch: SchoolChapter, opts: { model: string; runId: string; now: Date }): NotesProvenance {
  return {
    pipeline: SCHOOL_PIPELINE,
    promptVersion: NOTES_PROMPT_VERSION,
    model: opts.model,
    runId: opts.runId,
    producedAt: opts.now.toISOString(),
    class: ch.cls,
    examCode: ch.examCode,
    subject: ch.subject,
    book: ch.bookCode,
    bookTitle: ch.bookTitle,
    chapter: ch.chapterNumber,
    chapterTitle: ch.title,
    topicCode: ch.topicCode,
    officialUrl: ch.officialUrl,
    groundedIn: [`ncert-chapter-identity:${ch.examCode}:${ch.topicCode}`],
  };
}

export function provenanceComment(p: NotesProvenance): string {
  // "--" may not appear inside an HTML comment; the JSON has none, but keep it safe.
  return `${PROVENANCE_COMMENT_PREFIX}${JSON.stringify(p).replace(/--/g, "- -")} -->`;
}

export interface NoteWritePlan {
  topicId: string;
  where: { topicId: string };
  create: { topicId: string; content: string; generatedAt: Date; generatedBy: string };
  update: { content: string; generatedAt: Date; generatedBy: string; validatedAt: null; validatorId: null };
  provenance: NotesProvenance;
}

/** The upsert for one chapter's notes (content = validated markdown from parseSchoolNotes + the provenance comment). */
export function planNoteWrite(ch: SchoolChapter, content: string, opts: { model: string; runId: string; now: Date }): NoteWritePlan {
  const provenance = notesProvenance(ch, opts);
  const stored = `${content.trimEnd()}\n\n${provenanceComment(provenance)}\n`;
  const generatedBy = notesGeneratedBy(opts.model);
  return {
    topicId: ch.topicId,
    where: { topicId: ch.topicId },
    create: { topicId: ch.topicId, content: stored, generatedAt: opts.now, generatedBy },
    update: { content: stored, generatedAt: opts.now, generatedBy, validatedAt: null, validatorId: null },
    provenance,
  };
}

// ── Questions ───────────────────────────────────────────────────────────

/** The honest, student-readable label stored with every school question. */
export function questionLabel(ch: SchoolChapter): string {
  return `Practice question written by AI for ${chapterIdentity(ch)} — Shishya's own, not an NCERT exercise or a board question.`;
}

export interface SchoolQuestionProvenance {
  pipeline: typeof SCHOOL_PIPELINE;
  generatedBy: string;
  promptVersion: string;
  groundedSources: string[];
  producedAt: string;
  label: string;
  school: {
    class: number;
    examCode: string;
    subject: string;
    book: string;
    bookTitle: string;
    chapter: string | null;
    chapterTitle: string;
    topicCode: string;
    officialUrl: string;
    setIndex: number;
    runId: string;
  };
}

const KEBAB = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
/** Model tags kept per question after the three fixed ones. */
export const MODEL_TAGS_MAX = 3;

export function questionTags(ch: SchoolChapter, candidate: Pick<CandidateQuestion, "tags">, now: Date): string[] {
  const fixed = [ch.topicCode, SCHOOL_TAG, genTag(now)];
  const own = [...new Set(candidate.tags.map((t) => t.trim().toLowerCase()).filter((t) => KEBAB.test(t) && t.length <= 40 && !fixed.includes(t)))].slice(0, MODEL_TAGS_MAX);
  return [...fixed, ...own];
}

export type QuestionRowPlan = Omit<Prisma.QuestionUncheckedCreateInput, "metadata"> & { metadata: { provenance: SchoolQuestionProvenance } };

/** The create rows for one set's clean, deduplicated candidates. */
export function planQuestionRows(
  ch: SchoolChapter,
  examId: string,
  candidates: CandidateQuestion[],
  opts: { model: string; runId: string; setIndex: number; now: Date },
): QuestionRowPlan[] {
  const producedAt = opts.now.toISOString();
  const label = questionLabel(ch);
  return candidates.map((c) => ({
    examId,
    topicId: ch.topicId,
    type: "MCQ",
    difficulty: c.difficulty,
    body: c.body,
    options: c.options,
    answerKey: c.answerKey,
    solution: c.solution,
    language: "EN",
    source: "AI_GENERATED",
    validated: false,
    validatedBy: null,
    validatedAt: null,
    tags: questionTags(ch, c, opts.now),
    pyqYear: null,
    metadata: {
      provenance: {
        pipeline: SCHOOL_PIPELINE,
        generatedBy: opts.model,
        promptVersion: MCQ_PROMPT_VERSION,
        groundedSources: [`ncert-chapter-identity:${ch.examCode}:${ch.topicCode}`, `topic.teachingNote:${ch.topicCode}`],
        producedAt,
        label,
        school: {
          class: ch.cls,
          examCode: ch.examCode,
          subject: ch.subject,
          book: ch.bookCode,
          bookTitle: ch.bookTitle,
          chapter: ch.chapterNumber,
          chapterTitle: ch.title,
          topicCode: ch.topicCode,
          officialUrl: ch.officialUrl,
          setIndex: opts.setIndex,
          runId: opts.runId,
        },
      },
    },
  }));
}

